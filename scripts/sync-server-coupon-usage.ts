import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';

interface Property {
  type?: string | string[];
  const?: unknown;
  enum?: unknown[];
  pattern?: string;
}
interface Definition {
  type: string;
  additionalProperties: boolean;
  properties: Record<string, Property>;
  required: string[];
}
interface Contract {
  $id: string;
  'x-zdp-transport': Record<string, unknown>;
  $defs: Record<string, Definition>;
}
const root = resolve(import.meta.dir, '..');
const args = process.argv.slice(2);
if (args.some((arg) => arg !== '--check')) throw new Error('Only --check is supported');
for(const kind of ['capture','compensation'] as const) {
const sourcePath = resolve(root, `../zdp-api-contracts/contracts/apis/money-api/coupon-usage-${kind}.schema.json`);
const target = resolve(root, `src/server-coupon-usage/${kind==='capture'?'models':'compensation-models'}.ts`);
const prefix=kind==='capture'?'CouponUsageCapture':'CouponUsageCompensation';
const constant=kind==='capture'?'COUPON_USAGE':'COUPON_COMPENSATION';
const source = await readFile(sourcePath, 'utf8');
const contract = JSON.parse(source) as Contract;
const hash = createHash('sha256').update(source).digest('hex');
let output = `// Generated by scripts/sync-server-coupon-usage.ts; do not edit.\n// Source: ${contract.$id}\n// SHA-256: ${hash}\n\n`;
for (const [definition, name] of [['request', `${prefix}Request`], ['response', `${prefix}Receipt`]] as const) {
  const shape = contract.$defs[definition];
  if (!shape || shape.type !== 'object' || shape.additionalProperties !== false
    || shape.required.length !== Object.keys(shape.properties).length) throw new Error('Unsupported capture schema');
  output += `export interface ${name} {\n`;
  for (const [field, property] of Object.entries(shape.properties)) {
    if (!/^[a-z_]+$/.test(field) || !shape.required.includes(field)) throw new Error('Unsupported field');
    let type: string;
    if ('const' in property) type = JSON.stringify(property.const);
    else if (property.enum) type = property.enum.map((value) => JSON.stringify(value)).join(' | ');
    else {
      const kinds = Array.isArray(property.type) ? property.type : [property.type];
      if (kinds.some((kind) => !['string', 'boolean', 'null'].includes(kind ?? ''))) throw new Error('Unsupported field type');
      type = kinds.join(' | ');
    }
    output += `  readonly ${field}: ${type};\n`;
  }
  output += '}\n\n';
}
output += `export const ${constant}_TRANSPORT = ${JSON.stringify(contract['x-zdp-transport'], null, 2)} as const;\n\n`;
output += `export const ${constant}_RECEIPT_RULES = ${JSON.stringify(contract.$defs.response?.properties, null, 2)} as const;\n`;
if (args.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Server coupon usage models drifted from the API contract');
  console.log('Server coupon usage contract drift check passed.');
} else {
  await mkdir(resolve(root, 'src/server-coupon-usage'), { recursive: true });
  await writeFile(target, output);
  console.log('Server coupon usage models generated.');
}
}
